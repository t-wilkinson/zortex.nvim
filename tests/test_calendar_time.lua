local T = require("helpers")
local CT = require("zortex.features.calendar_time")

T.test("offsets: 1h30m, 90m, 1:30, -15m", function()
	T.eq(CT.parse_offset("1h30min"), 90)
	T.eq(CT.parse_offset("1h30m"), 90)
	T.eq(CT.parse_offset("1h 30m"), 90)
	T.eq(CT.parse_offset("90m"), 90)
	T.eq(CT.parse_offset("90"), 90)
	T.eq(CT.parse_offset("1:30"), 90)
	T.eq(CT.parse_offset("2h"), 120)
	T.eq(CT.parse_offset("-15m"), -15)
	T.eq(CT.parse_offset("+1.5h"), 90)
	T.eq(CT.parse_offset("soon"), nil)
	T.eq(CT.parse_offset(""), nil)
	T.eq(CT.format_offset(90), "1h30m")
	T.eq(CT.format_offset(-15), "-15m")
end)

T.test("shifting a line moves the entry's times, not the text's", function()
	local function shift(line, m)
		return (CT.shift_line(line, m))
	end
	T.eq(shift("12:00 Lunch", 90), "13:30 Lunch")
	T.eq(shift("- 09:00 Stand-up", 15), "- 09:15 Stand-up")
	T.eq(shift("  16:00 [ ] Call Sam", -30), "  15:30 [ ] Call Sam")
	T.eq(shift("09:00 - 10:30 Deep work", 60), "10:00 - 11:30 Deep work")
	T.eq(shift("- Read John 3:16 @at(9:05)", 60), "- Read John 3:16 @at(10:05)")
	T.eq(shift("- Trip @from(2026-10-20 08:00) @to(2026-10-20 17:00)", 30), "- Trip @from(2026-10-20 08:30) @to(2026-10-20 17:30)")
	T.eq(shift("- [ ] No time here", 60), "- [ ] No time here")
	T.eq(select(2, CT.shift_line("- [ ] No time here", 60)), 0)
	-- out of the day: left alone
	T.eq(CT.shift_line("23:30 Late", 60), nil)
	T.eq(CT.shift_line("00:10 Early", -15), nil)
end)

T.test("shifting a selection is one change; lines that would leave the day stay", function()
	local buf = vim.api.nvim_create_buf(false, true)
	vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "**2026-10-20:**", "09:00 A", "- [ ] B", "23:00 C", "10:00 - 11:00 D" })
	local changed, skipped = CT.shift_lines(buf, 2, 5, 90)
	T.eq({ changed, skipped }, { 2, 1 })
	T.eq(vim.api.nvim_buf_get_lines(buf, 0, -1, false), { "**2026-10-20:**", "10:30 A", "- [ ] B", "23:00 C", "11:30 - 12:30 D" })
	vim.api.nvim_buf_delete(buf, { force = true })
end)

T.test("now: the latest entry that has started", function()
	local lines = { "**2026-10-20:**", "Outcomes:", "- [ ] Ship", "", "07:00 Run", "09:00 - 10:30 Deep work", "- [ ] Untimed", "12:30 Lunch", "", "**2026-10-21:**", "08:00 Next day" }
	T.eq(CT.line_for_time(lines, 1, "10:00", "2026-10-20"), 6)
	T.eq(CT.line_for_time(lines, 1, "12:30", "2026-10-20"), 8)
	T.eq(CT.line_for_time(lines, 1, "23:59", "2026-10-20"), 8, "not into the next day")
	T.eq(CT.line_for_time(lines, 1, "06:00", "2026-10-20"), nil)
end)
