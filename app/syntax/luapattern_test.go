func TestLuaPatternRegexp(t *testing.T) {
	for _, c := range luaPatternCases {
		re, err := LuaPatternRegexp(c.pattern)
		if err != nil {
			t.Fatalf("%q: %v", c.pattern, err)
		}
		if got := re.MatchString(c.text); got != c.match {
			t.Errorf("%q on %q: got %v, Lua says %v (%s)", c.pattern, c.text, got, c.match, re)
		}
	}
	for _, bad := range []string{"[", "%b()", "%f[%w]", "(%1)", "%", "(x"} {
		if _, err := LuaPatternRegexp(bad); err == nil {
			t.Errorf("%q: want an error", bad)
		}
	}
}
